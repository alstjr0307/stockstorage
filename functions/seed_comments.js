function spreadDates(pickCreatedAt, count) {
  const start = pickCreatedAt.toDate ? pickCreatedAt.toDate() : new Date(pickCreatedAt);
  const now = new Date();
  const totalMs = now - start;
  return Array.from({ length: count }, (_, i) => {
    const ratio = Math.pow((i + 1 + Math.random() * 0.8) / (count + 1), 1.5);
    const jitter = (Math.random() - 0.5) * totalMs * 0.04;
    return new Date(start.getTime() + totalMs * ratio + jitter);
  }).sort((a, b) => a - b);
}

async function seedComments() {
  const picksSnap = await db.collection('stock_picks').get();
  console.log(`종목 ${picksSnap.size}개 발견\n`);

  for (const doc of picksSnap.docs) {
    const pick = doc.data();
    const ticker = pick.ticker;
    const name = pick.name || ticker;
    const pickCreatedAt = pick.createdAt;

    if (!pickCreatedAt || !commentsByTicker[ticker]) {
      console.log(`[SKIP] ${name} (${ticker})`);
      continue;
    }

    // 기존 seed 댓글 삭제
    const existingSnap = await db.collection('stock_picks').doc(doc.id).collection('comments').get();
    const deleteBatch = db.batch();
    existingSnap.docs.forEach(d => {
      if ((d.data().uid || '').startsWith('seed_u')) deleteBatch.delete(d.ref);
    });
    await deleteBatch.commit();

    const items = commentsByTicker[ticker];
    const dates = spreadDates(pickCreatedAt, items.length);

    const batch = db.batch();
    items.forEach(({ u, t }, i) => {
      const ref = db.collection('stock_picks').doc(doc.id).collection('comments').doc();
      batch.set(ref, {
        uid: u.uid,
        displayName: u.name,
        text: t,
        createdAt: admin.firestore.Timestamp.fromDate(dates[i]),
      });
    });

    await batch.commit();
    console.log(`[OK] ${name} (${ticker}) — 댓글 ${items.length}개`);
  }

  console.log('\n완료!');
  process.exit(0);
}

