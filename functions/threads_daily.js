'use strict';
const {randomUUID}=require('node:crypto');
const {getFirestore}=require('firebase-admin/firestore');
const {getStorage}=require('firebase-admin/storage');
const {getApp}=require('firebase-admin/app');
const {SecretManagerServiceClient}=require('@google-cloud/secret-manager');
const {ThreadsGraph,BLOCKED}=require('./threads_graph');
const {createThreadsDraft}=require('./threads_content');
const {renderThreadsImages}=require('./threads_visual');
const {fresh,isThreadsSource,analysisHash}=require('./social_analysis');
const {VERSION}=require('./threads_editorial');
const dayKey=date=>new Date(date.getTime()+9*3600000).toISOString().slice(0,10);
function eligible(prior,now=new Date()) {
  if(BLOCKED.has(prior?.status))return false;
  if((prior?.attempts||0)>=3)return false;
  const until=prior?.leaseUntil?.toDate?.()||new Date(prior?.leaseUntil||0);
  return !prior||until<=now;
}
async function loadToken(configRef,config) {
  const project=getApp().options.projectId||process.env.GCLOUD_PROJECT;
  const client=new SecretManagerServiceClient(),parent=`projects/${project}/secrets/THREADS_ACCESS_TOKEN`;
  const [version]=await client.accessSecretVersion({name:`${parent}/versions/latest`});
  let token=version.payload.data.toString();
  const refreshed=config.tokenRefreshedAt?.toDate?.()||new Date(0);
  if(Date.now()-refreshed.getTime()>7*86400000) {
    const response=await fetch('https://graph.threads.net/refresh_access_token?grant_type=th_refresh_token',{headers:{Authorization:`Bearer ${token}`},signal:AbortSignal.timeout(60000)});
    const data=await response.json();
    if(!response.ok||!data.access_token)throw new Error('THREADS_TOKEN_REFRESH_FAILED');
    token=data.access_token;
    await client.addSecretVersion({parent,payload:{data:Buffer.from(token)}});
    await configRef.set({tokenRefreshedAt:new Date(),tokenExpiresAt:new Date(Date.now()+Number(data.expires_in)*1000)},{merge:true});
  }
  return token;
}
async function runDailyThreads(options={}) {
  const db=options.db||getFirestore(),now=options.now||new Date(),day=dayKey(now);
  const configRef=db.collection('_admin').doc('threadsAutomation'),config=(await configRef.get()).data()||{};
  if(config.enabled!==true&&!options.draftOnly)return {status:'disabled'};
  if(!options.draftOnly&&!config.account)throw new Error('THREADS_ACCOUNT_REQUIRED');
  // Reuse today's verified analysis generated by the existing Instagram scheduler.
  const source=await db.collection('_admin').doc('instagramAutomation').collection('jobs').where('day','==',day).get();
  const candidates=source.docs.filter(d=>isThreadsSource(d.id,d.data(),now));
  if(!candidates.length){await configRef.set({lastRunAt:new Date(),lastRunStatus:'waiting_for_fresh_analysis'},{merge:true});return {status:'waiting_for_fresh_analysis'};}
  let graph;
  if(!options.draftOnly){graph=options.graph||new ThreadsGraph(await loadToken(configRef,config),config.account);await graph.identity();}
  const results=[];
  for(const item of candidates) {
    const analysis=item.data().analysis,key=item.id+(options.draftOnly?'_preview':'');
    const ref=configRef.collection('jobs').doc(key),owner=randomUUID();
    const previous=(await ref.get()).data();
    const claimed=await db.runTransaction(async tx=>{const prior=(await tx.get(ref)).data();if(!eligible(prior,now))return false;tx.set(ref,{status:'generating',attempts:(prior?.attempts||0)+1,owner,day,sourceJob:item.id,startedAt:new Date(),leaseUntil:new Date(Date.now()+30*60000)},{merge:true});return true;});
    if(!claimed){results.push({key,status:'already_handled'});continue;}
    let phase='generating';
    const save=async fields=>{await db.runTransaction(async tx=>{if((await tx.get(ref)).data()?.owner!==owner)throw new Error('THREADS_LEASE_LOST');tx.set(ref,{...fields,updatedAt:new Date()},{merge:true});});if(fields.status)phase=fields.status;};
    try {
      const usage=[...(previous?.editorialUsage||[])];
      const draft=previous?.draft?.editorialVersion===VERSION&&previous.analysisHash===analysisHash(analysis)
        ? (previous.draft.editorial?await createThreadsDraft(analysis,{editorial:previous.draft.editorial}):previous.draft)
        : await (options.createDraft||createThreadsDraft)(analysis,{onUsage:async record=>{usage.push({...record,usage:record.usage||null});await save({editorialUsage:usage});}});
      await save({status:'draft',analysis,draft,analysisId:item.data().analysisId||item.id,analysisHash:analysisHash(analysis)});
      const images=await (options.render||renderThreadsImages)(analysis,draft);
      if(images.length!==2)throw new Error('THREADS_TWO_IMAGES_REQUIRED');
      if(options.draftOnly){await save({status:'preview_complete',leaseUntil:new Date(0)});results.push({key,status:'preview_complete'});continue;}
      // Do not publish if generation crossed a market date boundary.
      if(!fresh(analysis,new Date()))throw new Error('THREADS_STALE_ANALYSIS');
      const bucket=getStorage().bucket(config.storageBucket||'stockstorage-13828.firebasestorage.app'),urls=[];
      for(let i=0;i<images.length;i++){
        const name=`threads/${key}/${owner}/${i+1}.jpg`,token=randomUUID();
        await bucket.file(name).save(images[i],{resumable:false,contentType:'image/jpeg',metadata:{metadata:{firebaseStorageDownloadTokens:token},cacheControl:'public,max-age=86400'}});
        urls.push(`https://firebasestorage.googleapis.com/v0/b/${bucket.name}/o/${encodeURIComponent(name)}?alt=media&token=${token}`);
      }
      await save({status:'uploading',imageUrls:urls});
      const ids=await graph.publish(draft,urls,save);
      await configRef.set({lastPublishedAt:new Date(),lastJob:key,lastMediaId:ids[0]},{merge:true});
      results.push({key,status:'published'});
    }catch(error){
      const code=/^[A-Z0-9_]+$/.test(error.message||'')?error.message:'THREADS_JOB_FAILED';
      if(phase!=='published')await save({status:phase==='publishing'?'publish_uncertain':'failed',error:code,leaseUntil:new Date(0)});
      results.push({key,status:phase==='published'?'published':phase==='publishing'?'publish_uncertain':'failed',error:code});
    }
  }
  await configRef.set({lastRunAt:new Date(),lastRunStatus:results.some(r=>['failed','publish_uncertain'].includes(r.status))?'failed':'complete',lastRunResults:results},{merge:true});
  if(results.some(r=>['failed','publish_uncertain'].includes(r.status)))throw new Error('THREADS_DAILY_PARTIAL_FAILURE');
  return {status:'complete',results};
}
module.exports={runDailyThreads,eligible,fresh};
